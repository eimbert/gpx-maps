const { chromium } = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.NAVIGATION_TEST_URL || 'http://127.0.0.1:4201';
const output = path.join(__dirname, '../tmp/navigation-qa');
fs.mkdirSync(output, { recursive: true });
const gpx = fs.readFileSync(path.join(__dirname, '../src/assets/track.gpx'), 'utf8');
const track = { id: 901, title: 'Vuelta por el Pirineo', fileName: 'pirineo.gpx', routeId: null, province: 'Huesca', autonomousCommunity: 'Aragón', population: 'Aínsa', distanceKm: 32.5, ascentMeters: 740, timeSeconds: 7200, uploadedAt: '2026-10-01', createdBy: 901 };
(async () => {
  const browser = await chromium.launch({ channel: 'chrome', headless: true });
  const errors = [];
  try {
    for (const width of (process.env.NAVIGATION_TEST_WIDTHS || '390,1440').split(',').map(Number)) {
      const context = await browser.newContext({ viewport: { width, height: 900 }, isMobile: width < 600 });
      await context.route('http://localhost:8081/**', route => {
        const url = new URL(route.request().url());
        if (/^\/routes\/\d+$/.test(url.pathname)) return route.fulfill({ status: 404, json: { message: 'Route not found' } });
        let json = [];
        if (url.pathname === '/auth/me') json = { userId: 901, nom: 'Prueba', nickname: 'prueba', plan: 'FREE' };
        if (url.pathname === '/tracks/me' || url.pathname === '/tracks/shared') json = [track];
        if (url.pathname === '/tracks/901/gpx') json = { id: 901, fileName: 'pirineo.gpx', routeXml: gpx };
        if (url.pathname.includes('destination')) json = { description: 'Recorridos de montaña por el Pirineo.' };
        return route.fulfill({ json });
      });
      const page = await context.newPage();
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(base);
      await page.getByRole('link', { name: /Archivo de rutas/ }).waitFor();
      assert.equal(await page.locator('.home__actions a').count(), 4);
      await page.screenshot({ path: path.join(output, `home-${width}.png`), fullPage: true });
      await page.getByRole('link', { name: /Animar una ruta/ }).click();
      await page.getByRole('button', { name: /Descubrir ruta.*Elegir ruta/ }).waitFor();
      assert.equal(await page.locator('#routeArchive').count(), 0);
      await page.screenshot({ path: path.join(output, `animation-${width}.png`), fullPage: true });
      await page.getByRole('button', { name: /Descubrir ruta.*Elegir ruta/ }).click();
      await page.locator('input[type=file]').first().setInputFiles({ name: 'ruta.gpx', mimeType: 'application/gpx+xml', buffer: Buffer.from(gpx) });
      await page.getByRole('heading', { name: '1 track seleccionado', exact: true }).waitFor();
      await page.getByRole('button', { name: 'Archivo', exact: true }).click();
      await page.getByRole('heading', { name: 'Tu archivo empieza aquí' }).waitFor();
      await page.getByRole('button', { name: 'Iniciar sesión', exact: true }).click();
      await page.getByRole('dialog').waitFor();
      await page.keyboard.press('Escape');
      await page.getByRole('button', { name: 'Animar', exact: true }).click();
      await page.getByRole('heading', { name: '1 track seleccionado', exact: true }).waitFor();
      await page.screenshot({ path: path.join(output, `setup-${width}.png`), fullPage: true });
      await page.getByRole('button', { name: 'Configurar animación' }).click();
      await page.getByRole('button', { name: 'Continuar', exact: true }).click();
      await page.getByRole('dialog').getByRole('heading', { name: 'Descubrir ruta', exact: true }).waitFor();
      assert.equal(await page.locator('.animation-choices').count(), 0);
      await page.getByText('Duración automática', { exact: true }).waitFor();
      assert.equal(await page.locator('.animation-more-options').getAttribute('open'), null);
      await page.getByText('Más opciones', { exact: true }).click();
      await page.getByLabel('9:16 (vertical)').check();
      await page.screenshot({ path: path.join(output, `options-${width}.png`) });
      await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
      await page.getByRole('button', { name: 'Cambiar', exact: true }).click();
      await page.getByRole('button', { name: /Animar carrera.*Elegir tracks/ }).click();
      await page.getByRole('heading', { name: '1 track seleccionado', exact: true }).waitFor();
      await page.getByRole('button', { name: 'Configurar animación' }).click();
      await page.getByRole('button', { name: 'Continuar', exact: true }).click();
      await page.getByRole('dialog').getByRole('heading', { name: 'Animar carrera', exact: true }).waitFor();
      assert.equal(await page.getByLabel('Duración del vídeo').count(), 0);
      await page.getByRole('button', { name: 'Cancelar', exact: true }).click();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      // An isolated mock session tests the archive without using a real account.
      const token = 'mock.' + Buffer.from(JSON.stringify({ exp: Math.floor(Date.now()/1000)+3600 })).toString('base64url') + '.mock';
      await page.evaluate(token => localStorage.setItem('gpxAuthSession', JSON.stringify({ token, id: 901, nickname: 'prueba', verified: true, exitCode: 0 })), token);
      await page.goto(`${base}/load?mode=routes&view=archive`);
      await page.locator('.destination-card').first().waitFor();
      assert.equal(await page.locator('.animation-types').count(), 0);
      await page.screenshot({ path: path.join(output, `archive-${width}.png`), fullPage: true });
      await page.getByLabel('Filtrar tracks guardadas').fill('Pirineo');
      await page.locator('.destination-card').first().click();
      await page.locator('.route-explorer-card').getByRole('button', { name: 'Animar', exact: true }).click();
      await page.getByRole('button', { name: /Descubrir ruta.*Elegir ruta/ }).waitFor();
      await page.getByRole('button', { name: /Animar carrera.*Elegir tracks/ }).click();
      await page.getByRole('heading', { name: '1 track seleccionado', exact: true }).waitFor();
      await page.getByRole('button', { name: /Elegir del archivo/ }).click();
      await page.locator('.route-explorer-card').getByRole('button', { name: /Elegir track/ }).click();
      await page.getByRole('heading', { name: '2 tracks seleccionados', exact: true }).waitFor();
      await page.getByRole('button', { name: /Quitar/ }).first().click();
      await page.getByRole('heading', { name: '1 track seleccionado', exact: true }).waitFor();
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      await page.getByRole('button', { name: 'Configurar animación' }).click();
      await page.getByRole('button', { name: 'Continuar', exact: true }).click();
      await page.getByRole('dialog').getByRole('heading', { name: 'Animar carrera', exact: true }).waitFor();
      await page.getByRole('button', { name: 'Continuar', exact: true }).click();
      await page.waitForURL('**/map?**');
      const payload = await page.evaluate(() => JSON.parse(sessionStorage.getItem('gpxViewerPayload')));
      assert.equal(payload.tipoAnimacion, 'carrera');
      assert.equal(payload.tracks.length, 1);
      await page.goto(base + '/load?mode=routes&view=archive');
      await page.locator('.destination-card').first().click();
      await page.locator('.route-explorer-card').getByRole('button', { name: 'Ver ruta', exact: true }).click();
      await page.waitForURL('**/map?from=archive');
      await page.getByRole('button', { name: width < 600 ? 'Volver' : 'Anterior', exact: true }).click();
      await page.waitForURL('**/load?mode=routes&view=archive');
      await page.getByRole('heading', { name: 'Archivo de rutas', exact: true }).waitFor();
      console.log(`PASS ${width}px: home, guest upload, mode choice, settings, cancellation, archive, search, selection and track preservation`);
      await context.close();
    }
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
